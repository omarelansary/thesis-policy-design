#!/usr/bin/env python3
"""PreToolUse guard (deterministic). Configured in .claude/settings.json; fires for the lead and for every subagent.

Enforces, as far as a hook can:
  1. No direct tool access to the research repository, previous-thesis folders, or earlier session transcripts
     (Read/Grep/Glob path arguments; Bash/PowerShell command text). The sanctioned route is tools/origin_extract.py.
  2. Single-writer ownership: a named subagent may write only inside the globs listed for it in config/ownership.json.
  3. Immutable files: nobody may Write/Edit evidence/governing/**, evidence/sources.json, evidence/restricted.json,
     evidence/origin-index.tsv, config/origin.json, via the file-edit tools.
  4. Agents may not edit configuration, instructions, tools or the authorization register.
Limits (see ops/SAFEGUARDS.md): Bash/PowerShell command text is matched by substring, so an obfuscated command or an
interpreter one-liner can evade rule 1; rule 3 does not cover writes made through Bash. verify_workspace.py detects
tampering after the fact.
Exit code 2 blocks the call and returns the stderr message to the model. Other failures are fail-closed via onFailure=block.
"""
import fnmatch, json, pathlib, re, sys

WS = pathlib.Path(__file__).resolve().parents[1]
data = json.load(sys.stdin)
tool = data.get("tool_name", "")
ti = data.get("tool_input", {}) or {}
agent = data.get("agent_type")  # absent for the lead session

FORBIDDEN_PATH = re.compile(
    r"research-cleanroom|thesis-backups|claude_forensic_rescue|[\\/]\.claude[\\/](projects|history|file-history|plans|backups|session-env)",
    re.I)
SANCTIONED = re.compile(r"tools[\\/]+origin_extract\.py|tools[\\/]+verify_workspace\.py", re.I)
IMMUTABLE = ["evidence/governing/**", "evidence/sources.json", "evidence/restricted.json", "evidence/origin-index.tsv", "config/origin.json"]
AGENT_FORBIDDEN_WRITE = [".claude/**", "CLAUDE.md", "tools/**", "config/**", "ops/AUTHORIZATIONS.md", "ops/STATE.md", ".gitignore", ".gitattributes"]


def block(msg):
    print("BLOCKED by tools/guard.py: " + msg, file=sys.stderr)
    sys.exit(2)


def rel(p):
    p = str(p).replace("\\", "/")
    ws = str(WS).replace("\\", "/")
    if p.lower().startswith(ws.lower() + "/"):
        return p[len(ws) + 1:]
    return p


def match(path, globs):
    path = path.lstrip("./")
    for g in globs:
        pat = g.replace("**", "\u0000").replace("*", "[^/]*").replace("\u0000", ".*")
        if re.fullmatch(pat, path):
            return True
    return False


if tool in ("Bash", "PowerShell"):
    cmd = ti.get("command", "")
    if FORBIDDEN_PATH.search(cmd) and not SANCTIONED.search(cmd):
        block("this command names the research repository, previous-thesis folders or earlier transcripts. "
              "Use `python tools/origin_extract.py` for evidence; ask the human to authorize anything else.")
elif tool in ("Read", "Grep", "Glob"):
    for k in ("file_path", "path", "pattern"):
        v = ti.get(k)
        if isinstance(v, str) and FORBIDDEN_PATH.search(v):
            block(f"direct access to '{v}' is not allowed. Use `python tools/origin_extract.py`.")
elif tool in ("Write", "Edit", "NotebookEdit", "MultiEdit"):
    p = ti.get("file_path") or ti.get("notebook_path") or ""
    r = rel(p)
    if FORBIDDEN_PATH.search(str(p)):
        block("writing to the research repository or session stores is not allowed.")
    if re.match(r"^[A-Za-z]:/|^/", r) and not str(r).lower().startswith("c:/users/omr/documents/thesis-policy-design"):
        block(f"writes outside the workspace are not allowed: {p}")
    if match(r, IMMUTABLE):
        block(f"{r} is immutable (generated by tools/build_origin_snapshot.py; changes need a human-authorized re-snapshot).")
    if agent:
        own = json.loads((WS / "config" / "ownership.json").read_text(encoding="utf-8"))
        if match(r, AGENT_FORBIDDEN_WRITE):
            block(f"agent '{agent}' may not edit {r} (configuration, instructions, tools and the authorization register belong to the lead and the human).")
        allowed = own.get("agents", {}).get(agent)
        if allowed is None:
            block(f"agent type '{agent}' has no write ownership entry in config/ownership.json; write nothing.")
        if not match(r, allowed):
            block(f"single-writer rule: agent '{agent}' may write only {allowed}; {r} belongs to another owner. "
                  "Send the content to its owner with SendMessage instead.")
sys.exit(0)
